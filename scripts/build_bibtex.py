#!/usr/bin/env python3
"""Generate a BibTeX entry for every paper in data/papers.csv, written to data/papers.bib.

Usage
-----
  python3 scripts/build_bibtex.py              # add entries for papers that have none yet
  python3 scripts/build_bibtex.py --refresh    # regenerate every entry that is not marked as checked
  python3 scripts/build_bibtex.py --check      # validate papers.bib / bibtex_checked.txt (no network)

Metadata comes from the DOI (doi.org content negotiation, CSL JSON), otherwise from the
`citation_*` meta tags of the proceedings page (PMLR, NeurIPS, JMLR, OpenReview), otherwise
from the CSV row itself (arXiv-only papers become @misc with eprint fields). Entries are
written in one style: keys like fong2023martingale (first author's surname, year, first
word of the title), title and venue taken from the CSV, proper nouns and acronyms in the
title protected with braces, accents as LaTeX commands.

Human checking
--------------
data/bibtex_checked.txt lists the keys of entries someone has checked by hand, one per
line ('#' starts a comment). Checked entries are never overwritten, so you can edit
them freely in papers.bib; the website shows them with a "checked" mark. To check an
entry: compare it with the published version, fix papers.bib if needed, add its key to
bibtex_checked.txt. Unchecked entries are kept too, unless you pass --refresh.

Only the Python standard library is used.
"""
import argparse
import json
import re
import sys
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_graph  # noqa: E402
from build_graph import fold, get, load_papers  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
BIB = ROOT / "data" / "papers.bib"
CHECKED = ROOT / "data" / "bibtex_checked.txt"

HEADER = """\
% BibTeX entries for the papers in data/papers.csv, generated by scripts/build_bibtex.py.
% Keys listed in data/bibtex_checked.txt have been checked by hand and are never regenerated;
% the others are machine-generated: please check before relying on them.
"""

# CSV venue -> (entry type, journal/booktitle, series)
VENUES = {
    "NeurIPS": ("inproceedings", "Advances in Neural Information Processing Systems", ""),
    "ICML": ("inproceedings", "Proceedings of the International Conference on Machine Learning", "Proceedings of Machine Learning Research"),
    "AISTATS": ("inproceedings", "Proceedings of the International Conference on Artificial Intelligence and Statistics", "Proceedings of Machine Learning Research"),
    "UAI": ("inproceedings", "Proceedings of the Conference on Uncertainty in Artificial Intelligence", "Proceedings of Machine Learning Research"),
    "Algorithmic Learning Theory (ALT)": ("inproceedings", "Proceedings of the International Conference on Algorithmic Learning Theory", "Proceedings of Machine Learning Research"),
    "Symposium on Advances in Approximate Bayesian Inference (AABI)": ("inproceedings", "Proceedings of the Symposium on Advances in Approximate Bayesian Inference", "Proceedings of Machine Learning Research"),
    "ICLR": ("inproceedings", "International Conference on Learning Representations", ""),
    "Handbook of Statistics": ("incollection", "Handbook of Statistics", ""),
    "Journal of the Royal Statistical Society: Series B": ("article", "Journal of the Royal Statistical Society: Series B (Statistical Methodology)", ""),
    "Journal of the Royal Statistical Society Series B: Statistical Methodology": ("article", "Journal of the Royal Statistical Society: Series B (Statistical Methodology)", ""),
    "Annals of Statistics": ("article", "The Annals of Statistics", ""),
}

# Words a sentence-case bibliography style must not lower-case.
PROPER = {
    "bayes", "bayesian", "gaussian", "kalman", "markov", "monte", "carlo", "gibbs", "cox", "renyi", "dirichlet",
    "wasserstein", "stein", "fisher", "kullback", "leibler", "hellinger", "bernstein", "hilbert", "laplace",
    "poisson", "student", "langevin", "hamiltonian", "bregman", "polya", "chernoff", "hoeffding", "pac",
}
STOP = {"a", "an", "the", "on", "of", "for", "in", "to", "and", "with", "from", "via", "is", "are", "at", "by", "towards", "toward"}
FIELD_ORDER = ["author", "title", "journal", "booktitle", "series", "volume", "number", "pages", "year",
               "publisher", "doi", "url", "eprint", "archiveprefix", "primaryclass", "note"]
FIELD_NAME = {"archiveprefix": "archivePrefix", "primaryclass": "primaryClass"}

ACCENTS = {"́": "'", "̀": "`", "̈": '"', "̂": "^", "̃": "~", "̧": "c",
           "̌": "v", "̄": "=", "̆": "u", "̊": "r", "̇": ".", "̋": "H", "̨": "k"}
SPECIAL = {"ø": r"{\o}", "Ø": r"{\O}", "ß": r"{\ss}", "ł": r"{\l}", "Ł": r"{\L}", "æ": r"{\ae}", "Æ": r"{\AE}",
           "œ": r"{\oe}", "đ": r"{\dj}", "ı": r"{\i}", "–": "--", "—": "---", "’": "'", "‘": "`", "“": "``",
           "”": "''", "&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", " ": "~"}
GREEK = {"α": r"\alpha", "β": r"\beta", "γ": r"\gamma", "δ": r"\delta", "ε": r"\varepsilon", "η": r"\eta",
         "θ": r"\theta", "κ": r"\kappa", "λ": r"\lambda", "μ": r"\mu", "ν": r"\nu", "π": r"\pi", "ρ": r"\rho",
         "σ": r"\sigma", "τ": r"\tau", "φ": r"\phi", "χ": r"\chi", "ψ": r"\psi", "ω": r"\omega"}


# ---------------------------------------------------------------- LaTeX helpers
def latex(s, math=False):
    out = []
    for ch in unicodedata.normalize("NFC", s or ""):
        if math and ch in GREEK:
            out.append(GREEK[ch] + " ")
        elif ch in SPECIAL and not (math and ch in "_&%#"):
            out.append(SPECIAL[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            d = unicodedata.normalize("NFD", ch)
            if len(d) == 2 and d[1] in ACCENTS and ord(d[0]) < 128:
                base = r"\i" if d[0] == "i" else d[0]
                out.append("{\\" + ACCENTS[d[1]] + ("{" + base + "}" if ACCENTS[d[1]].isalpha() else base) + "}")
            elif ch in GREEK:
                out.append("$" + GREEK[ch] + "$")
            else:
                out.append(ch)
    return re.sub(r"(\\[a-z]+) (?=[^a-z])", r"\1", "".join(out))


def protect_title(title):
    parts = re.split(r"(\$[^$]*\$)", title)
    out = []
    for i, part in enumerate(parts):
        if i % 2:  # maths
            out.append(latex(part, math=True))
            continue
        toks = []
        for tok in re.split(r"(\s+)", part):
            m = re.fullmatch(r"([^\w]*)([\w][\w'’\-]*[\w]|[\w])([^\w]*)", tok)
            if not m:
                toks.append(latex(tok))
                continue
            lead, core, trail = m.groups()
            pieces = re.split(r"[-'’]", core)
            plain = fold(core).split()
            needs = any(re.search(r"[A-Z]", pc[1:]) for pc in pieces) or any(w in PROPER for w in plain)
            if needs and re.search(r"[A-Z]", core):
                toks.append(latex(lead) + "{" + latex(core) + "}" + latex(trail))
            else:
                toks.append(latex(tok))
        out.append("".join(toks))
    return "".join(out)


PARTICLES = {"van", "von", "der", "den", "de", "del", "della", "di", "da", "du", "le", "la", "dos", "das", "ter"}


def split_name(full):
    words = full.split()
    if len(words) == 1:
        return "", full
    i = len(words) - 1
    while i > 1 and words[i - 1].lower() in PARTICLES:
        i -= 1
    return " ".join(words[:i]), " ".join(words[i:])


def bib_author(given, family):
    return latex(f"{family}, {given}" if given else family)


def make_key(family, year, title, taken):
    fam = fold(re.sub(r"^(?:van|von|de|del|della|di|da|du|le|la)\s+", "", family or "anon", flags=re.I)).replace(" ", "")
    word = next((w for w in fold(title).split() if w not in STOP and not w.isdigit()), "paper")
    base = f"{fam}{year}{word}"
    key, n = base, 0
    while key in taken:
        n += 1
        key = base + "abcdefghijklmnopqrstuvwxyz"[n]
    return key


# ---------------------------------------------------------------- metadata
def csl_for_doi(doi):
    """CSL JSON from doi.org (works for Crossref and DataCite DOIs). Cached like the graph lookups."""
    url = "https://doi.org/" + urllib.parse.quote(doi, safe="/")
    cache_url = url + "#csl"
    import hashlib
    path = build_graph.CACHE / hashlib.sha1(cache_url.encode()).hexdigest()
    if path.exists() and not build_graph.REFRESH:
        return json.loads(path.read_text(encoding="utf-8"))
    req = urllib.request.Request(url, headers={**build_graph.UA, "Accept": "application/vnd.citationstyles.csl+json"})
    try:
        with urllib.request.urlopen(req, timeout=40) as r:
            data = json.loads(r.read().decode("utf-8", "ignore"))
    except (urllib.error.URLError, json.JSONDecodeError, TimeoutError) as e:
        print(f"    DOI lookup failed for {doi}: {e}", file=sys.stderr)
        return None
    build_graph.CACHE.mkdir(exist_ok=True)
    path.write_text(json.dumps(data), encoding="utf-8")
    return data


def page_meta(url):
    try:
        txt = get(url, 1.0)
    except Exception as e:
        print(f"    page fetch failed for {url}: {e}", file=sys.stderr)
        return {}
    meta = {}
    for name, content in re.findall(r'<meta\s+name="(citation_[a-z_]+)"\s+content="([^"]*)"', txt or ""):
        meta.setdefault(name, []).append(content)
    return meta


def build_entry(p, taken):
    aid, doi, url = p["_aid"], p["_doi"], p["published"]
    kind, venue, series = VENUES.get(p["venue"], ("article", p["venue"], ""))
    f = {}
    authors = None
    if p["venue"] == "arXiv preprint" or not url:
        kind = "misc"
    elif doi and (csl := csl_for_doi(doi)):
        authors = [(a.get("given", ""), a.get("family") or a.get("literal", "")) for a in csl.get("author", [])]
        f["volume"] = str(csl.get("volume", "") or "")
        f["number"] = str(csl.get("issue", "") or "")
        f["pages"] = (csl.get("page") or "").replace("-", "--").replace("–", "--")
        if kind == "incollection" or csl.get("type") in ("chapter", "book-chapter"):
            kind = "incollection"
            f["publisher"] = csl.get("publisher", "")
        if p["venue"] not in VENUES and csl.get("type") in ("paper-conference", "proceedings-article"):
            kind = "inproceedings"
            venue = csl.get("container-title") or venue
        f["doi"] = re.search(r"10\.\d{4,9}/[^\s?#]+", url).group(0).rstrip(".")  # original case
    else:
        m = page_meta(url)
        if m.get("citation_author"):
            authors = []
            for a in m["citation_author"]:
                a = a.strip()
                authors.append(tuple(reversed([x.strip() for x in a.split(",", 1)])) if "," in a else split_name(a))
        first, last = (m.get("citation_firstpage") or [""])[0], (m.get("citation_lastpage") or [""])[0]
        f["pages"] = f"{first}--{last}" if first and last else first
        f["volume"] = (m.get("citation_volume") or [""])[0]
        pm = re.search(r"proceedings\.mlr\.press/v(\d+)/", url)
        if pm:
            f["volume"], f["publisher"] = pm.group(1), "PMLR"
            series = series or "Proceedings of Machine Learning Research"
        elif "jmlr.org/papers" in url:
            vm = re.search(r"/v(\d+)/", url)
            f["volume"] = vm.group(1) if vm else f["volume"]
            f["number"] = re.sub(r"\D", "", (m.get("citation_issue") or [""])[0])
        f["url"] = url
    csv_names = [a.strip() for a in p["authors"].split(",") if a.strip()]
    if not authors:
        authors = [split_name(a) for a in csv_names]
    elif len(authors) == len(csv_names):
        # Prefer the curated full names from the CSV (Crossref often has initials only),
        # keeping the source's split into given and family names when it agrees.
        authors = [(n[:-len(fam)].strip(), fam) if fam and n.endswith(fam) else split_name(n)
                   for n, (g, fam) in zip(csv_names, authors)]

    f["author"] = " and ".join(bib_author(g, fam) for g, fam in authors)
    f["title"] = protect_title(p["title"])
    if kind == "article":
        f["journal"] = latex(venue)
    elif kind in ("inproceedings", "incollection"):
        f["booktitle"] = latex(venue)
        if series:
            f["series"] = series
    f["year"] = p["year"]
    if aid:
        f["eprint"], f["archiveprefix"] = aid, "arXiv"
        if kind == "misc":
            f["url"] = "https://arxiv.org/abs/" + aid
    key = make_key(authors[0][1] if authors else "", p["year"], p["title"], taken)
    body = ",\n".join(f"  {FIELD_NAME.get(k, k)} = {{{f[k]}}}" for k in FIELD_ORDER if f.get(k))
    return key, f"@{kind}{{{key},\n{body}\n}}"


# ---------------------------------------------------------------- papers.bib I/O
def parse_bib(text):
    """Entries as dicts {key, type, text, fields}. Brace-balanced, good enough for our own file."""
    entries = []
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        depth, i = 1, m.end()
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body = text[m.end():i - 1]
        fields = {}
        for fm in re.finditer(r"(\w+)\s*=\s*", body):
            j = fm.end()
            if j < len(body) and body[j] == "{":
                d, k = 1, j + 1
                while k < len(body) and d:
                    d += {"{": 1, "}": -1}.get(body[k], 0)
                    k += 1
                fields.setdefault(fm.group(1).lower(), body[j + 1:k - 1])
        entries.append({"type": m.group(1).lower(), "key": m.group(2), "text": text[m.start():i], "fields": fields})
    return entries


def read_checked():
    if not CHECKED.exists():
        return []
    return [ln.split("#", 1)[0].strip() for ln in CHECKED.read_text(encoding="utf-8").splitlines()
            if ln.split("#", 1)[0].strip()]


def match_entry(p, entries):
    for e in entries:
        fl = e["fields"]
        if p["_aid"] and fl.get("eprint", "").strip() == p["_aid"]:
            return e
        if p["_doi"] and fl.get("doi", "").strip().lower() == p["_doi"]:
            return e
    t = fold(p["title"])
    for e in entries:
        if fold(re.sub(r"[{}\\]", "", e["fields"].get("title", ""))) == t:
            return e
    return None


def check(papers):
    bad = 0
    text = BIB.read_text(encoding="utf-8") if BIB.exists() else ""
    entries = parse_bib(text)
    keys = [e["key"] for e in entries]
    for k in sorted({k for k in keys if keys.count(k) > 1}):
        print(f"  papers.bib: duplicate key {k}")
        bad += 1
    for k in read_checked():
        if k not in keys:
            print(f"  bibtex_checked.txt: {k} is not a key in papers.bib")
            bad += 1
    missing = [p["title"] for p in papers if not match_entry(p, entries)]
    for t in missing:
        print(f"  warning: no BibTeX entry for {t[:70]!r} (run scripts/build_bibtex.py)")
    n_checked = len(set(read_checked()) & set(keys))
    print(f"{len(entries)} BibTeX entries ({n_checked} checked by hand), {bad} problem(s) found." if bad
          else f"{len(entries)} BibTeX entries ({n_checked} checked by hand), no problems found.")
    return bad == 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate papers.bib and bibtex_checked.txt (no network)")
    ap.add_argument("--refresh", action="store_true", help="regenerate unchecked entries and ignore the download cache")
    args = ap.parse_args()
    papers = load_papers()
    if args.check:
        sys.exit(0 if check(papers) else 1)
    build_graph.REFRESH = args.refresh

    old = parse_bib(BIB.read_text(encoding="utf-8")) if BIB.exists() else []
    checked = set(read_checked())
    taken, out, new = set(), [], 0
    for i, p in enumerate(papers, 1):
        e = match_entry(p, old)
        if e and (e["key"] in checked or not args.refresh):
            taken.add(e["key"])
            out.append(e["text"])
            continue
        print(f"[{i}/{len(papers)}] {p['title'][:70]}", file=sys.stderr)
        key, text = build_entry(p, taken)
        if e and e["key"] not in taken:  # keep the old key so links and citations do not break
            text = text.replace("{" + key + ",", "{" + e["key"] + ",", 1)
            key = e["key"]
        taken.add(key)
        out.append(text)
        new += 1
    BIB.write_text(HEADER + "\n" + "\n\n".join(out) + "\n", encoding="utf-8")
    if not CHECKED.exists():
        CHECKED.write_text("# Keys of entries in data/papers.bib that have been checked by hand (one per line).\n"
                           "# Checked entries are never regenerated by scripts/build_bibtex.py.\n", encoding="utf-8")
    print(f"Wrote {BIB.relative_to(ROOT)}: {len(out)} entries ({new} generated now, "
          f"{len(checked & taken)} checked by hand).")


if __name__ == "__main__":
    main()
